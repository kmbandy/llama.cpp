#!/usr/bin/env python3
"""Emit the real DeepSeek-V4.1 per-layer stream layout as a C++ include.

Reads the KV metadata of a DS4.1 GGUF (gguf-py, no tensor data is touched)
and writes tests/test-dsv41-rowgroup-layout.inc, which the row-group end-to-end
test uses to give its tiny synthetic model the production layer table.

Usage: gen-dsv41-rowgroup-layout.py [GGUF] [OUT]
  GGUF defaults to ~/models/dsv41-spine-ml84.gguf
  OUT  defaults to tests/test-dsv41-rowgroup-layout.inc next to this script's repo

The trunk is the first `deepseek41.block_count - deepseek41.nextn_predict_layers`
layers (the MTP/nextn blocks are not part of the row-group trunk; the same
convention as /tmp/claude-1000/ss/sim_layers.py, NL=40).
"""
import os
import sys

GGUF_PY = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'gguf-py')
sys.path.insert(0, os.path.abspath(GGUF_PY))
from gguf import GGUFReader  # noqa: E402


def field(reader, key):
    f = reader.fields.get(key)
    if f is None:
        return None
    return f.contents()


def src_for(ids, il):
    """Mirror llama_hparams::dsv41_derive_stream_roles: last source <= il, else -1."""
    s = -1
    for x in ids:
        if x <= il:
            s = x
    return s


def main():
    gguf_path = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/models/dsv41-spine-ml84.gguf')
    out_path = sys.argv[2] if len(sys.argv) > 2 else os.path.normpath(os.path.join(
        os.path.dirname(os.path.abspath(__file__)), '..', 'tests', 'test-dsv41-rowgroup-layout.inc'))

    r = GGUFReader(gguf_path, 'r')
    block_count = int(field(r, 'deepseek41.block_count'))
    nextn = int(field(r, 'deepseek41.nextn_predict_layers') or 0)
    n_trunk = block_count - nextn
    ratios = [int(x) for x in field(r, 'deepseek41.attention.compress_ratios')]
    kv_src = [int(x) for x in field(r, 'deepseek41.attention.kv_source_layer_ids')]
    idx_src = [int(x) for x in field(r, 'deepseek41.attention.index_source_layer_ids')]
    engram = [int(x) for x in field(r, 'deepseek41.engram.layer_ids')]
    cand = int(field(r, 'deepseek41.attention.candidate_source_layer_id'))
    swa = int(field(r, 'deepseek41.attention.sliding_window'))
    swiglu = [float(x) for x in field(r, 'deepseek41.swiglu_clamp_exp')]

    assert len(ratios) >= n_trunk, 'compress_ratios shorter than the trunk'

    lines = []
    lines.append('// GENERATED by scripts/gen-dsv41-rowgroup-layout.py from %s -- do not edit.'
                 % os.path.basename(gguf_path))
    lines.append('// Real DeepSeek-V4.1 trunk layout (layers 0..n_trunk-1); the test builds a tiny')
    lines.append('// synthetic model on top of it.')
    lines.append('constexpr uint32_t rg_layout_n_layer      = %d;' % n_trunk)
    lines.append('constexpr uint32_t rg_layout_n_swa        = %d;' % swa)
    lines.append('constexpr uint32_t rg_layout_candidate_src = %d;' % cand)
    lines.append('constexpr uint32_t rg_layout_compress_ratios[%d] = {%s};'
                 % (n_trunk, ', '.join(str(x) for x in ratios[:n_trunk])))
    lines.append('constexpr uint32_t rg_layout_kv_source_ids[%d] = {%s};'
                 % (len(kv_src), ', '.join(str(x) for x in kv_src)))
    lines.append('constexpr uint32_t rg_layout_index_source_ids[%d] = {%s};'
                 % (len(idx_src), ', '.join(str(x) for x in idx_src)))
    lines.append('constexpr uint32_t rg_layout_engram_layer_ids[%d] = {%s};'
                 % (len(engram), ', '.join(str(x) for x in engram)))
    lines.append('constexpr float rg_layout_swiglu_clamp = %.1ff;' % swiglu[0])
    lines.append('')
    # Derived roles, for the test's own sanity checks (same rule as dsv41_derive_stream_roles).
    kv_derived = [src_for(kv_src, il) for il in range(n_trunk)]
    idx_derived = [src_for(idx_src, il) for il in range(n_trunk)]
    lines.append('constexpr int32_t rg_layout_kv_source[%d] = {%s};'
                 % (n_trunk, ', '.join(str(x) for x in kv_derived)))
    lines.append('constexpr int32_t rg_layout_topk_source[%d] = {%s};'
                 % (n_trunk, ', '.join(str(x) for x in idx_derived)))

    with open(out_path, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote %s (n_trunk=%d, kv=%s, idx=%s, engram=%s)' % (out_path, n_trunk, kv_src, idx_src, engram))


if __name__ == '__main__':
    main()
